"""Cross-implementation conformance: decode fixtures produced by the extension.

Fixtures are generated by `npm run fixtures -- python/tests/_fixtures` (the
extension's own core encodes and renders them). If these tests fail, the Python
decoder and the TypeScript encoder disagree on the format.
"""

from __future__ import annotations

import json
import os
import pathlib

import pytest
from stegoshard import WrongPasswordError, decode_any, decode_vault
from stegoshard.pipeline import MissingKeyError

FIXTURES = pathlib.Path(__file__).parent / "_fixtures"

#: Set by CI. Locally a missing fixture directory is a skip; in CI it is a hard
#: failure, so this suite can never quietly stop running. Same rule as
#: tests/compliance, tests/steganalysis and tests/erasure.
#:
#: It matters more here than anywhere else. These are the only cross-implementation
#: tests in the repository, and there are 25 of them. Under the old plain skipif,
#: a CI job whose `npm run fixtures` step had silently produced nothing would have
#: reported green while checking that the Python decoder and the TypeScript encoder
#: agree on absolutely nothing.
IN_CI = os.environ.get("CI") == "true"

if not FIXTURES.exists():
    _message = (
        "conformance fixtures not generated (run: npm run fixtures -- python/tests/_fixtures)"
    )
    pytestmark = (
        pytest.mark.skip(reason=_message)
        if not IN_CI
        else pytest.mark.usefixtures("_fixtures_are_required")
    )


@pytest.fixture
def _fixtures_are_required() -> None:
    pytest.fail(
        "conformance fixtures are missing under CI. This suite is the only "
        "cross-implementation check in the repository; skipping it would report "
        "green while verifying nothing."
    )


def _load(name: str):
    d = FIXTURES / name
    manifest = json.loads((d / "manifest.json").read_text())
    payloads = []
    for img in sorted(d.glob("page-*.png")):
        # decode_any picks the codec from the pixels, exactly as the apps do.
        # the fixtures carry no out-of-band hint about which one was used.
        payload = decode_any(img.read_bytes())
        assert payload is not None, f"failed to decode {img.name}"
        payloads.append(payload)
    expected = (d / "expected.bin").read_bytes()
    key_path = d / "vault.key"
    key = key_path.read_bytes() if key_path.exists() else None
    return manifest, payloads, expected, key


def test_embedded_round_trip():
    manifest, payloads, expected, _key = _load("embedded")
    restored = decode_vault(payloads, manifest["password"])
    assert restored.filename == manifest["filename"]
    assert restored.content == expected


def test_color_grid_round_trip():
    """The 8-colour grid (SPEC §2.2), branded exactly as the apps write it."""
    manifest, payloads, expected, _key = _load("color-grid")
    assert manifest["codec"] == "color-grid"
    restored = decode_vault(payloads, manifest["password"])
