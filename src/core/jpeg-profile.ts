/**
 * The one JPEG encoder profile every normalized cover is written with.
 *
 * WHY A PROFILE, AND WHY IT IS PINNED HERE
 * Cover normalization stopped being segment surgery: a photo that keeps its
 * maker's quantization tables, its ICC profile and 55 KB of base64 makernote in
 * an extended XMP packet reads as a scraped camera file even with every metadata
 * marker removed. So the covers are re-encoded, and the whole point is that they
 * all come out of the *same* encoder, whatever device they came from.
 *
 * That only works if the profile is pinned exhaustively rather than inherited
 * from a library's defaults. Every axis below is one a file can stand out on, and
 * library defaults move between versions: two builds of StegoShard emitting
 * different quantization tables would undo the entire exercise. Nothing here is
 * "whatever the encoder does"; `jpeg-encode.ts` reads these values and writes
 * exactly them, and `jpeg-profile.test.ts` asserts the bytes rather than the
 * settings.
 *
 * THE VALUES, AND WHERE THEY COME FROM
 * Quality 85, which is the most ordinary quality on the web and is what the
 * measurements this profile was chosen with used. The tables are the Annex K
 * (ITU T.81) base tables scaled by the libjpeg formula at that quality:
 *
 *     sf = quality < 50 ? floor(5000 / quality) : 200 - quality * 2      = 30
 *     q[i] = clamp(floor((base[i] * sf + 50) / 100), 1, 255)
 *
 * They are written out as literals instead of computed, because a computed table
 * is a table that changes when someone edits the formula; the test re-derives
 * them from the base tables and compares, so the derivation stays checkable
 * without the emitted bytes depending on it.
 *
 * WHY 85 AND NOT HIGHER
 * Not capacity, and not detectability: measured on the five camera photographs in
 * `tests/steganalysis/covers-jpeg/`, quality barely moved the distance between a
 * cover's coefficient histogram and its carrier's. What sets the ceiling is
 * double quantization. Re-encoding is only safe when the new table is *coarser*
 * than the source's, or the histogram grows the empty bins a detector can see.
 * The luma table below sums to 1109; quality 90 sums to 736, which is finer than
 * one of those five photographs (864) and would comb it. See `jpeg-encode.ts`
 * for the refusal that enforces this per photo.
 *
 * 4:2:0, because it is what phones and cameras overwhelmingly write. Baseline
 * sequential, no restart interval, no ICC, no EXIF, no XMP, no JFIF thumbnail:
 * the segment sequence is SOI, APP0, DQT, SOF0, DHT, SOS, EOI and nothing else.
 */

