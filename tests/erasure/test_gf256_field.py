def test_typescript_field_parameters(ts_field: dict[str, Any]) -> None:
    assert ts_field["poly"] == EXPECTED_POLY, (
        f"typescript reducing polynomial is {ts_field['poly']:#x}, expected "
        f"{EXPECTED_POLY:#x} (SPEC.md §7.1)"
    )
    assert ts_field["generator"] == EXPECTED_GENERATOR


def test_typescript_dump_is_complete(ts_field: dict[str, Any]) -> None:
    """The dump has to cover the whole field before its silence means anything.

    A truncated dump would make every sweep below pass over whatever it happened
    to contain, which is the shape of green this suite exists to refuse.
    """
    assert len(bytes.fromhex(ts_field["mul"])) == PRODUCTS
    assert len(bytes.fromhex(ts_field["div"])) == QUOTIENTS
    assert len(bytes.fromhex(ts_field["inv"])) == INVERSES
    assert len(bytes.fromhex(ts_field["exp"])) == 255
    assert len(bytes.fromhex(ts_field["log"])) == 256


def test_typescript_products_match(ts_field: dict[str, Any], reedsolo_field: Any) -> None:
    mul = bytes.fromhex(ts_field["mul"])
    check_products("typescript", lambda a, b: mul[a * 256 + b], reedsolo_field)


def test_typescript_quotients_match(ts_field: dict[str, Any], reedsolo_field: Any) -> None:
    div = bytes.fromhex(ts_field["div"])
    check_quotients("typescript", lambda a, b: div[a * 255 + (b - 1)], reedsolo_field)


def test_typescript_inverses_match(ts_field: dict[str, Any], reedsolo_field: Any) -> None:
    inv = bytes.fromhex(ts_field["inv"])
    check_inverses("typescript", lambda a: inv[a - 1], reedsolo_field)


def test_typescript_exp_log_tables_match(ts_field: dict[str, Any], reedsolo_field: Any) -> None:
    check_tables(
        "typescript",
        list(bytes.fromhex(ts_field["exp"])),
        list(bytes.fromhex(ts_field["log"])),
        reedsolo_field,
    )


# --------------------------------------------------------------------------
# The two stacks against each other
# --------------------------------------------------------------------------


def test_both_stacks_agree(py_field: Any, ts_field: dict[str, Any]) -> None:
    """Cheap, and it separates two failures that want different reactions.

    If this passes while the sweeps above fail, both stacks drifted together and
    the specification is what to check. If this fails, one of them drifted and the
    other is the reference.
    """
    mul = bytes.fromhex(ts_field["mul"])
    bad = [
        f"{a:#04x}*{b:#04x}: py={py_field.gf_mul(a, b):#04x} ts={mul[a * 256 + b]:#04x}"
        for a in range(256)
        for b in range(256)
        if py_field.gf_mul(a, b) != mul[a * 256 + b]
    ]
    _report("python vs typescript", bad, PRODUCTS)


