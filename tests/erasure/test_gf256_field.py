def test_frozen_vectors_match_the_reference_field(reedsolo_field: Any) -> None:
    """The vector file has to be checked against something other than its author.

    ``tests/vectors/crypto-vectors.json`` was generated by the TypeScript stack,
    so vitest and pytest reproducing it proves the two stacks agree - the same
    thing they already agreed on before. Without this test the numbers would be a
    frozen snapshot of our own output, which is exactly the kind of self-reference
    this suite was built to break.
    """
    import json

    from conftest import REPO_ROOT

    gf = json.loads(
        (REPO_ROOT / "tests" / "vectors" / "crypto-vectors.json").read_text(encoding="utf-8")
    )["gf256"]

    assert gf["poly"] == EXPECTED_POLY
    assert gf["generator"] == EXPECTED_GENERATOR

    bad: list[str] = []
    for v in gf["products"]:
        # Both arms, so a vector cannot be blessed by the tabled path alone.
        for ref in (
            reedsolo_field.gf_mul(v["a"], v["b"]),
            reedsolo_field.gf_mult_noLUT(v["a"], v["b"], EXPECTED_POLY, 256),
        ):
            if v["product"] != ref:
                bad.append(f"{v['a']:#04x}*{v['b']:#04x}: frozen {v['product']:#04x} vs {ref:#04x}")
    for v in gf["quotients"]:
        ref = reedsolo_field.gf_div(v["a"], v["b"])
        if v["quotient"] != ref:
            bad.append(f"{v['a']:#04x}/{v['b']:#04x}: frozen {v['quotient']:#04x} vs {ref:#04x}")
    for v in gf["inverses"]:
        ref = reedsolo_field.gf_inverse(v["a"])
        if v["inverse"] != ref:
            bad.append(f"{v['a']:#04x}^-1: frozen {v['inverse']:#04x} vs {ref:#04x}")
    assert not bad, "frozen vectors disagree with the reference field: " + ", ".join(bad)


def test_frozen_vectors_would_not_survive_the_aes_field(reedsolo_field: Any) -> None:
    """The vectors must actually discriminate, not merely be reproducible.

    A vector set drawn from products that never overflow eight bits is identical
    in every GF(2^8) and pins nothing. This checks the committed pairs really do
    separate this field from the one they are most likely to be confused with.
    """
    import json

    from conftest import REPO_ROOT

    products = json.loads(
        (REPO_ROOT / "tests" / "vectors" / "crypto-vectors.json").read_text(encoding="utf-8")
    )["gf256"]["products"]

    differing = sum(
        1
        for v in products
        if v["product"] != reedsolo_field.gf_mult_noLUT(v["a"], v["b"], 0x11B, 256)
    )
    print(f"\n  {differing} of {len(products)} frozen products differ under the AES field 0x11B")
    assert differing == len(products), (
        f"only {differing} of {len(products)} committed products distinguish 0x11D from "
        "0x11B. A product that agrees across fields is decoration; replace it with one "
        "that reduces."
    )
